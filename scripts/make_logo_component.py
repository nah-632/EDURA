#!/usr/bin/env python3
"""
Generate app/src/components/brand/EduraLogo.tsx from the brand v2 SVGs.

Composition, not duplication: the module holds ONE copy of the mark paths and
ONE copy of the wordmark paths, and places them with the transforms recorded in
brand/v2/lockup-geometry.json. Baking six pre-composed SVGs would have cost
~120 KB of React; this costs ~25 KB.

Paths are inlined rather than fetched because the logo is the LCP element on
the homepage.

Run: python3 scripts/make_logo_component.py
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BRAND = f"{ROOT}/brand/v2"
OUT = f"{ROOT}/app/src/components/brand/EduraLogo.tsx"


def body_of(svg_text):
    return re.search(r"<svg[^>]*>(.*)</svg>", svg_text, re.S).group(1).strip()


def path_ds(chunk):
    return re.findall(r'<path d="([^"]+)"', chunk)


def make_group(attrs, ds, indent="      "):
    """Keep EVERY attribute of the source group. The vectoriser emits its
    layers with `transform="translate(0,H) scale(0.1,-0.1)"` because potrace
    works in tenths of a pixel; dropping it renders the mark at 10x and it
    overflows the lockup viewBox."""
    inner = "\n".join(f'{indent}  <path d="{d}" />' for d in ds)
    return f'{indent}<g {attrs}>\n{inner}\n{indent}</g>'


def main():
    mark = open(f"{BRAND}/edura-mark.svg").read()
    mark_vb = [float(v) for v in re.search(r'viewBox="([^"]+)"', mark).group(1).split()][2:]
    word = open(f"{BRAND}/edura-logo-wordmark.svg").read()
    shadow = body_of(word)
    word_fill = re.search(r'fill="(#[0-9A-Fa-f]{6})"', shadow).group(1)
    word_ds = path_ds(shadow)
    geo = json.load(open(f"{BRAND}/lockup-geometry.json"))

    # mark, split back into its three colour layers by their fill attribute
    layers = []
    for m in re.finditer(r"<g ([^>]*?)>(.*?)</g>", body_of(mark), re.S):
        attrs = m.group(1).strip()
        if 'fill="#' not in attrs:
            continue
        layers.append((attrs, path_ds(m.group(2))))
    assert len(layers) == 3, f"expected 3 mark layers, found {len(layers)}"

    all_mark_ds = [d for _, ds in layers for d in ds]
    # the mono variant inherits fill from <svg>; the transform must stay
    mark_transforms = [re.search(r'transform="([^"]+)"', a).group(1)
                       if 'transform="' in a else None for a, _ in layers]

    def group_js(indent="      "):
        return "\n".join(make_group(attrs, ds, indent) for attrs, ds in layers)

    def flat_js(ds, indent="      "):
        return "\n".join(f'{indent}<path d="{d}" />' for d in ds)

    tsx = f'''/**
 * EDURA logo.
 *
 * GENERATED by scripts/make_logo_component.py from brand/v2/*.svg - do not
 * hand-edit the path data.
 *
 * The mark is the sailboat whose bow is a pen nib, vectorised from the
 * client's brand kit board. The wordmark is Poppins, outlines extracted at
 * build time. Full colour is the default because the identity is built on
 * three colours; `variant="mono"` paints with currentColor for dark,
 * photographic or single-colour surfaces.
 */
import type {{ SVGProps }} from "react";

export interface LogoProps extends Omit<SVGProps<SVGSVGElement>, "children"> {{
  /** rendered height in px; width follows the artwork's aspect ratio */
  height?: number;
  title?: string;
  /** single-colour: inherits currentColor */
  variant?: "full" | "mono";
}}

export type LogoForm = "horizontal" | "stacked";

const WORD_FILL = "{word_fill}";
/* potrace emits its layers in tenths of a pixel, so each colour layer carries
   its own transform. Keeping it here is what stops the mark rendering at 10x. */
const MARK_VB = {mark_vb} as const;
const LOCKUP = {{
  horizontal: {{ width: {geo["horizontal"]["width"]}, height: {geo["horizontal"]["height"]},
    mark: "{geo["horizontal"]["markTransform"]}", word: "{geo["horizontal"]["wordTransform"]}" }},
  stacked: {{ width: {geo["stacked"]["width"]}, height: {geo["stacked"]["height"]},
    mark: "{geo["stacked"]["markTransform"]}", word: "{geo["stacked"]["wordTransform"]}" }},
}} as const;

/* eslint-disable react/jsx-key */
const MARK_COLOUR = (
  <>
{group_js()}
  </>
);

const MARK_PATHS = (
  <>
{flat_js(all_mark_ds, "    ")}
  </>
);

const WORD_PATHS = (
  <>
{flat_js(word_ds, "    ")}
  </>
);
/* eslint-enable react/jsx-key */

export function EduraMark({{ height = 32, title, variant = "full", ...rest }}: LogoProps) {{
  const [vbW, vbH] = MARK_VB;
  return (
    <svg
      viewBox={{`0 0 ${{vbW}} ${{vbH}}`}}
      width={{Math.round((height * vbW) / vbH)}}
      height={{height}}
      role={{title ? "img" : "presentation"}}
      aria-label={{title}}
      aria-hidden={{title ? undefined : true}}
      focusable="false"
      {{...(variant === "mono" ? {{ fill: "currentColor" }} : {{}})}}
      {{...rest}}
    >
      {{title ? <title>{{title}}</title> : null}}
      {{variant === "mono" ? MARK_PATHS : MARK_COLOUR}}
    </svg>
  );
}}

export function EduraLogo({{
  height = 30,
  title,
  markOnly = false,
  form = "horizontal",
  variant = "full",
  ...rest
}}: LogoProps & {{ markOnly?: boolean; form?: LogoForm }}) {{
  if (markOnly) {{
    return <EduraMark height={{height}} title={{title}} variant={{variant}} {{...rest}} />;
  }}
  const box = LOCKUP[form];
  const [vbW, vbH] = [box.width, box.height];
  return (
    <svg
      viewBox={{`0 0 ${{vbW}} ${{vbH}}`}}
      width={{Math.round((height * vbW) / vbH)}}
      height={{height}}
      role={{title ? "img" : "presentation"}}
      aria-label={{title}}
      aria-hidden={{title ? undefined : true}}
      focusable="false"
      {{...(variant === "mono" ? {{ fill: "currentColor" }} : {{}})}}
      {{...rest}}
    >
      {{title ? <title>{{title}}</title> : null}}
      <g transform={{box.mark}}>{{variant === "mono" ? MARK_PATHS : MARK_COLOUR}}</g>
      <g transform={{box.word}} fill={{variant === "mono" ? "currentColor" : WORD_FILL}}>
        {{WORD_PATHS}}
      </g>
    </svg>
  );
}}
'''
    open(OUT, "w").write(tsx)
    print(f"wrote {OUT} ({len(tsx) / 1024:.1f} KB) - "
          f"{len(all_mark_ds)} mark paths + {len(word_ds)} wordmark paths")


main()
